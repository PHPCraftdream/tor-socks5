//! Persistent pool of **unverified** bridge candidates.
//!
//! Fetching bridge lists (network → public collectors) is decoupled from
//! probing them (network → the bridges) and from using them (the working
//! config that arti bootstraps on):
//!
//! * a **refresh** fetches the source lists and merges the newcomers here,
//!   deduplicated and minus anything already in the working config;
//! * a **drain** walks this pool lazily (one bridge at a time), promotes
//!   the reachable ones into the working config, and removes every probed
//!   candidate from the pool (reachable → promoted, dead → discarded,
//!   deferred → moved to the back of the queue).
//!
//! Stored next to the active config as `<stem>.candidates.log`, a scratch
//! staging file (plain bridge lines, one per line):
//!
//! ```text
//! # Auto-generated by tor-socks5. Unverified bridge candidate pool.
//! obfs4 1.2.3.4:80 ABCDEF... cert=... iat-mode=0
//! webtunnel [2001:db8::1]:443 0123... url=https://example.com/x ver=0.0.3
//! ```
//!
//! Deduplication uses the canonical `BridgeIdentity` shared by all consumers.
//! The identity preserves the full WebTunnel carrier target and certificate.
//! Writers (refresh, drain) run their whole load→mutate→save cycle as one
//! cross-process transaction ([`CandidatePool::transaction`] or an explicitly
//! held [`persist_lock::PathLock`]): daemon maintenance and the
//! `bridges fetch` CLI serialize on the per-path lock instead of publishing
//! whole files over each other's snapshot.

use std::collections::HashSet;
use std::fs;
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicU64, Ordering};

use anyhow::{Context, Result};
use bridge_line::BridgeLine;
use bridge_probe::{bridge_identity, BridgeIdentity};

use persist_lock::{PathLock, POOL_LOCK_WAIT};

const HEADER: &str = "# Auto-generated by tor-socks5. Unverified bridge candidate pool.";
const DEFAULT_FILE: &str = "tor-socks5.candidates.log";
static SAVE_SEQ: AtomicU64 = AtomicU64::new(0);

/// Dedup key shared with the config, fetcher and health store.
pub type Key = BridgeIdentity;

pub fn key_of(b: &BridgeLine) -> Key {
    bridge_identity(b)
}

#[derive(Debug)]
pub struct CandidatePool {
    path: PathBuf,
    /// Insertion-ordered candidates, deduplicated by [`key_of`].
    bridges: Vec<BridgeLine>,
    keys: HashSet<Key>,
}

impl CandidatePool {
    /// Pool transaction lock: held from the load through the save, so
    /// competing refresh/drain writers serialize instead of racing
    /// whole-file renames. The bounded wait runs on the blocking pool — a
    /// lock wait must never block an async worker.
    pub(crate) async fn acquire_transaction_lock(path: &Path) -> Result<PathLock> {
        let path = path.to_path_buf();
        tokio::task::spawn_blocking(move || {
            PathLock::acquire_bounded(&path, POOL_LOCK_WAIT)
                .with_context(|| format!("candidate pool transaction lock for {}", path.display()))
        })
        .await
        .map_err(|e| anyhow::anyhow!("candidate pool lock task failed: {e}"))?
    }

    /// One whole cross-process read-modify-write: transaction lock → load →
    /// mutate → save. What `f` removes stays removed — the published file is
    /// the freshly loaded pool mutated by `f`, never a union with a stale
    /// snapshot, so consumed/dead entries cannot be resurrected. Sync: the
    /// lock wait blocks; async flows holding the lock across awaits use
    /// [`CandidatePool::acquire_transaction_lock`] directly.
    pub fn transaction<T>(path: &Path, f: impl FnOnce(&mut CandidatePool) -> T) -> Result<T> {
        #[cfg(test)]
        crate::test_seams::park_if_armed(crate::test_seams::Site::PreAcquire, path);
        let _lock = PathLock::acquire_bounded(path, POOL_LOCK_WAIT)
            .with_context(|| format!("candidate pool transaction lock for {}", path.display()))?;
        let mut pool = CandidatePool::load(path.to_path_buf())?;
        #[cfg(test)]
        crate::test_seams::park_if_armed(crate::test_seams::Site::PostLoad, path);
        let out = f(&mut pool);
        pool.save()?;
        Ok(out)
    }

    /// Resolve the pool path from the config path: same dir + stem, fixed
    /// `.candidates.log` suffix (mirrors the alive-bridges log). Falls back
    /// to `./tor-socks5.candidates.log` for built-in defaults.
    pub fn resolve_path(config_path: Option<&Path>) -> PathBuf {
        match config_path {
            Some(cfg) => {
                let dir = cfg.parent().unwrap_or_else(|| Path::new("."));
                let stem = cfg
                    .file_stem()
                    .map(|s| s.to_string_lossy().into_owned())
                    .unwrap_or_else(|| "tor-socks5".to_string());
                dir.join(format!("{stem}.candidates.log"))
            }
            None => PathBuf::from(DEFAULT_FILE),
        }
    }

    /// Load the pool, ignoring malformed/duplicate lines. Missing file →
    /// empty pool.
    pub fn load(path: PathBuf) -> Result<Self> {
        persist_lock::cleanup_temp_files(&path);
        let mut pool = Self {
            path,
            bridges: Vec::new(),
            keys: HashSet::new(),
        };
        let text = match fs::read_to_string(&pool.path) {
            Ok(s) => s,
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(pool),
            Err(e) => return Err(e).with_context(|| format!("read {}", pool.path.display())),
        };
        for raw in text.lines() {
            let line = raw.trim();
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            if let Ok(bridge) = line.parse::<BridgeLine>() {
                pool.push_unique(bridge);
            }
        }
        Ok(pool)
    }

    fn push_unique(&mut self, bridge: BridgeLine) -> bool {
        let key = key_of(&bridge);
        if self.keys.insert(key) {
            self.bridges.push(bridge);
            true
        } else {
            false
        }
    }

    /// Merge fetched candidates, skipping any already present in the pool
    /// or whose key is in `exclude` (the working set). Returns how many
    /// were newly added.
    pub fn merge(
        &mut self,
        fetched: impl IntoIterator<Item = BridgeLine>,
        exclude: &HashSet<Key>,
    ) -> usize {
        let mut added = 0;
        for bridge in fetched {
            if exclude.contains(&key_of(&bridge)) {
                continue;
            }
            if self.push_unique(bridge) {
                added += 1;
            }
        }
        added
    }

    /// Remove and return up to `n` candidates from the front of the pool.
    pub fn take(&mut self, n: usize) -> Vec<BridgeLine> {
        let n = n.min(self.bridges.len());
        let taken: Vec<BridgeLine> = self.bridges.drain(..n).collect();
        for b in &taken {
            self.keys.remove(&key_of(b));
        }
        taken
    }

    /// Select across the whole pool; other transports keep their queue positions.
    pub fn take_transport(&mut self, n: usize, transport: Option<&str>) -> Vec<BridgeLine> {
        let Some(transport) = transport else {
            return self.take(n);
        };
        if n == 0 || self.bridges.is_empty() {
            return Vec::new();
        }
        // One pass: move out the first `n` matches; the scan stops as soon
        // as the batch is complete and the rest keeps its relative order.
        let mut taken = Vec::new();
        let mut kept = Vec::with_capacity(self.bridges.len().saturating_sub(n));
        let mut rest = std::mem::take(&mut self.bridges).into_iter();
        for bridge in rest.by_ref() {
            if bridge.transport.as_deref() == Some(transport) {
                taken.push(bridge);
                if taken.len() == n {
                    break;
                }
            } else {
                kept.push(bridge);
            }
        }
        kept.extend(rest);
        self.bridges = kept;
        for bridge in &taken {
            self.keys.remove(&key_of(bridge));
        }
        taken
    }

    pub fn prioritize(&mut self, fresh: &[BridgeLine], transport: Option<&str>) {
        // The full dedup key ([`key_of`]) must match merge/exclude: a
        // shortened key would mark a stale variant of a relay as fresh
        // alongside the actual tested-list entry. Keys for `fresh` are built
        // once up front; sort_by_cached_key computes each pool key once and
        // keeps the sort stable.
        let fresh_keys: HashSet<Key> = fresh
            .iter()
            .filter(|bridge| transport.is_none_or(|name| bridge.transport.as_deref() == Some(name)))
            .map(key_of)
            .collect();
        self.bridges
            .sort_by_cached_key(|bridge| !fresh_keys.contains(&key_of(bridge)));
    }

    /// Remove exactly the given bridges, matched by the full identity key
    /// ([`key_of`]); returns how many entries were removed. The drain's
    /// confirm step runs this on a freshly loaded pool under the
    /// transaction lock, shedding only its own outcomes — entries a
    /// concurrent writer merged in the meantime are untouched.
    pub fn remove_all(&mut self, bridges: &[BridgeLine]) -> usize {
        // One pass, not one retain per bridge: `key_of` reparses a WebTunnel
        // carrier URL, so a nested scan would pay that for every (pool entry,
        // request) pair.
        let mut removed = 0;
        let doomed: HashSet<Key> = bridges
            .iter()
            .map(key_of)
            .filter(|key| self.keys.remove(key))
            .inspect(|_| removed += 1)
            .collect();
        if removed > 0 {
            self.bridges.retain(|b| !doomed.contains(&key_of(b)));
        }
        removed
    }

    /// Move the given candidates to the back of the queue, keeping their
    /// relative order. Entries the pool no longer holds are ignored — a
    /// concurrent writer may have removed or promoted them, and rotation
    /// must not resurrect anything. The keys set is untouched: every moved
    /// entry goes straight back with the identity it already had. Runs
    /// inside the drain's confirm transaction on a freshly loaded pool, so
    /// an attempted-deferred batch goes behind everything the pool currently
    /// has, including newcomers a concurrent refresh merged in the meantime.
    pub fn rotate_to_back(&mut self, bridges: &[BridgeLine]) -> usize {
        let requested: HashSet<Key> = bridges.iter().map(key_of).collect();
        let mut rotated = Vec::new();
        self.bridges.retain(|bridge| {
            if requested.contains(&key_of(bridge)) {
                rotated.push(bridge.clone());
                false
            } else {
                true
            }
        });
        let count = rotated.len();
        self.bridges.extend(rotated);
        count
    }

    #[must_use]
    pub fn len(&self) -> usize {
        self.bridges.len()
    }

    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.bridges.is_empty()
    }

    /// Atomic write via [`persist_lock::TempFileGuard`]: a sibling temp
    /// whose name embeds pid + a monotonic counter for uniqueness, held
    /// under an advisory exclusive lock for the whole create→rename span, so
    /// a reader's cleanup only deletes a temp whose owner provably died (the
    /// kernel releases the lock on death). The final rename is atomic.
    pub fn save(&self) -> Result<()> {
        let mut out = String::new();
        out.push_str(HEADER);
        out.push('\n');
        out.push('\n');
        for b in &self.bridges {
            out.push_str(&b.to_string());
            out.push('\n');
        }
        let seq = SAVE_SEQ.fetch_add(1, Ordering::Relaxed);
        let mut guard = persist_lock::TempFileGuard::create(&self.path, seq)?;
        guard.write_all(out.as_bytes())?;
        guard.finish()?;
        Ok(())
    }
}

